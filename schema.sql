CREATE INDEX IF NOT EXISTS telegram_messages_chat_id_idx
    ON public.telegram_messages(chat_id);

CREATE INDEX IF NOT EXISTS telegram_messages_sender_id_idx
    ON public.telegram_messages(sender_id);

CREATE INDEX IF NOT EXISTS telegram_messages_sent_at_utc_idx
    ON public.telegram_messages(sent_at_utc DESC);

CREATE INDEX IF NOT EXISTS telegram_messages_thread_idx
    ON public.telegram_messages(chat_id, message_thread_id);

CREATE INDEX IF NOT EXISTS telegram_messages_body_search_idx
    ON public.telegram_messages
    USING GIN (to_tsvector('simple', COALESCE(body, '') || ' ' || COALESCE(caption, '')));

CREATE INDEX IF NOT EXISTS telegram_message_reactions_message_idx
    ON public.telegram_message_reactions(chat_id, message_id);

CREATE INDEX IF NOT EXISTS telegram_message_reactions_user_idx
    ON public.telegram_message_reactions(user_id);

INSERT INTO public.telegram_chats (
    chat_id,
    chat_title,
    chat_username,
    chat_type,
    joined_at_utc,
    first_seen_at_utc,
    last_seen_at_utc,
    updated_at_utc
)
SELECT DISTINCT ON (chat_id)
    chat_id,
    chat_title,
    chat_username,
    chat_type,
    MIN(received_at_utc) OVER (PARTITION BY chat_id),
    MIN(received_at_utc) OVER (PARTITION BY chat_id),
    MAX(received_at_utc) OVER (PARTITION BY chat_id),
    NOW()
FROM public.telegram_messages
WHERE chat_id IS NOT NULL
ORDER BY chat_id, received_at_utc DESC
ON CONFLICT (chat_id) DO NOTHING;

CREATE OR REPLACE VIEW public.telegram_group_stats AS
SELECT
    c.chat_id,
    c.chat_title,
    c.chat_username,
    c.chat_type,
    c.joined_at_utc,
    c.first_seen_at_utc,
    c.last_seen_at_utc,
    COUNT(m.id)::BIGINT AS message_count,
    MAX(m.sent_at_utc) AS last_message_at_utc
FROM public.telegram_chats c
LEFT JOIN public.telegram_messages m ON m.chat_id = c.chat_id
GROUP BY
    c.chat_id,
    c.chat_title,
    c.chat_username,
    c.chat_type,
    c.joined_at_utc,
    c.first_seen_at_utc,
    c.last_seen_at_utc;

