CREATE TABLE IF NOT EXISTS public.telegram_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    update_id BIGINT NOT NULL,
    message_id BIGINT,
    chat_id BIGINT,
    chat_title TEXT,
    chat_username TEXT,
    chat_type TEXT,
    message_thread_id BIGINT,
    is_topic_message BOOLEAN,
    topic_name TEXT,
    topic_icon_color BIGINT,
    topic_icon_custom_emoji_id TEXT,
    sender_id BIGINT,
    sender_username TEXT,
    sender_first_name TEXT,
    sender_last_name TEXT,
    sender_is_bot BOOLEAN,
    sender_photo_file_id TEXT,
    sender_photo_file_unique_id TEXT,
    sender_chat_id BIGINT,
    sender_chat_title TEXT,
    body TEXT,
    caption TEXT,
    message_type TEXT,
    sent_at_utc TIMESTAMPTZ,
    sent_date DATE,
    sent_time TIME,
    edited_at_utc TIMESTAMPTZ,
    reply_to_message_id BIGINT,
    forward_origin_json JSONB,
    entities_json JSONB,
    media_file_id TEXT,
    media_group_id TEXT,
    raw_payload_json JSONB NOT NULL,
    received_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(update_id, message_id)
);

CREATE TABLE IF NOT EXISTS public.telegram_topics (
    chat_id BIGINT NOT NULL,
    message_thread_id BIGINT NOT NULL,
    topic_name TEXT,
    icon_color BIGINT,
    icon_custom_emoji_id TEXT,
    raw_payload_json JSONB,
    created_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (chat_id, message_thread_id)
);

CREATE TABLE IF NOT EXISTS public.telegram_chats (
    chat_id BIGINT PRIMARY KEY,
    chat_title TEXT,
    chat_username TEXT,
    chat_type TEXT,
    joined_at_utc TIMESTAMPTZ,
    first_seen_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    raw_payload_json JSONB,
    created_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.telegram_message_reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    update_id BIGINT NOT NULL,
    chat_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    user_id BIGINT,
    actor_chat_id BIGINT,
    reaction_type TEXT NOT NULL,
    reaction_emoji TEXT,
    custom_emoji_id TEXT,
    reaction_json JSONB NOT NULL,
    user_username TEXT,
    user_first_name TEXT,
    user_last_name TEXT,
    user_photo_file_id TEXT,
    user_photo_file_unique_id TEXT,
    reacted_at_utc TIMESTAMPTZ,
    raw_payload_json JSONB NOT NULL,
    received_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

