UPDATE public.visibility_roadmap_items
SET status = CASE status
    WHEN 'planned' THEN 'not_started'
    WHEN 'in_progress' THEN 'on_track'
    WHEN 'delivered' THEN 'delivered'
    WHEN 'blocked' THEN 'blocked'
    WHEN 'canceled' THEN 'canceled'
    ELSE status
END
WHERE status IN ('planned', 'in_progress', 'delivered', 'blocked', 'canceled');

