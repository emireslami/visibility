    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_item_id BIGINT NOT NULL REFERENCES public.visibility_roadmap_items(id) ON DELETE CASCADE,
    title TEXT NOT NULL CHECK (length(btrim(title)) BETWEEN 2 AND 180),
    expected_date DATE,
    expected_month SMALLINT,
    expected_week SMALLINT,
    status TEXT NOT NULL DEFAULT 'not_started',
    created_by_email TEXT,
    updated_by_email TEXT,
    created_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT visibility_roadmap_checkpoints_month_chk
        CHECK (expected_month IS NULL OR expected_month BETWEEN 6 AND 12),
    CONSTRAINT visibility_roadmap_checkpoints_week_chk
        CHECK (expected_week IS NULL OR expected_week BETWEEN 1 AND 4),
    CONSTRAINT visibility_roadmap_checkpoints_status_chk
        CHECK (status IN ('not_started', 'on_track', 'at_risk', 'blocked', 'delivered'))
);

CREATE INDEX IF NOT EXISTS visibility_roadmap_checkpoints_item_idx
