CREATE TABLE IF NOT EXISTS public.visibility_roadmap_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_roadmap_id BIGINT NOT NULL REFERENCES public.visibility_roadmap_items(id) ON DELETE CASCADE,
    consumer_roadmap_id BIGINT NOT NULL REFERENCES public.visibility_roadmap_items(id) ON DELETE CASCADE,
    need_by_date DATE,
    need_by_month SMALLINT,
    need_by_week SMALLINT,
    expected_delivery_date DATE,
    expected_delivery_month SMALLINT,
    expected_delivery_week SMALLINT,
    dependency_status TEXT NOT NULL DEFAULT 'on_track',
    description TEXT NOT NULL DEFAULT '',
    created_by_email TEXT,
    updated_by_email TEXT,
    created_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT visibility_roadmap_dependencies_not_self_chk
        CHECK (provider_roadmap_id <> consumer_roadmap_id),
    CONSTRAINT visibility_roadmap_dependencies_need_month_chk
        CHECK (need_by_month IS NULL OR need_by_month BETWEEN 6 AND 12),
    CONSTRAINT visibility_roadmap_dependencies_need_week_chk
        CHECK (need_by_week IS NULL OR need_by_week BETWEEN 1 AND 4),
    CONSTRAINT visibility_roadmap_dependencies_expected_month_chk
        CHECK (expected_delivery_month IS NULL OR expected_delivery_month BETWEEN 6 AND 12),
    CONSTRAINT visibility_roadmap_dependencies_expected_week_chk
        CHECK (expected_delivery_week IS NULL OR expected_delivery_week BETWEEN 1 AND 4),
    CONSTRAINT visibility_roadmap_dependencies_status_chk
        CHECK (dependency_status IN ('not_started', 'on_track', 'at_risk', 'blocked', 'delivered')),
    UNIQUE (provider_roadmap_id, consumer_roadmap_id)
);

CREATE INDEX IF NOT EXISTS visibility_roadmap_dependencies_provider_idx
    ON public.visibility_roadmap_dependencies (provider_roadmap_id);

CREATE INDEX IF NOT EXISTS visibility_roadmap_dependencies_consumer_idx
    ON public.visibility_roadmap_dependencies (consumer_roadmap_id);

ALTER TABLE public.visibility_roadmap_dependencies ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS visibility_roadmap_dependencies_no_public_access ON public.visibility_roadmap_dependencies;

CREATE POLICY visibility_roadmap_dependencies_no_public_access
    ON public.visibility_roadmap_dependencies
    FOR ALL
    USING (false)
    WITH CHECK (false);

INSERT INTO public.visibility_roadmap_dependencies (
    provider_roadmap_id,
    consumer_roadmap_id,
    need_by_date,
    need_by_month,
    need_by_week,
    expected_delivery_date,
    expected_delivery_month,
    expected_delivery_week,
    dependency_status,
    description,
    created_by_email,
    updated_by_email
)
SELECT
    child.id,
    parent.id,
    parent.delivery_date,
    parent.delivery_month,
    parent.delivery_week,
    child.delivery_date,
    child.delivery_month,
    child.delivery_week,
    CASE
        WHEN child.status = 'blocked' THEN 'blocked'
        WHEN child.status = 'delivered' THEN 'delivered'
        WHEN child.delivery_date > parent.delivery_date THEN 'at_risk'
        ELSE 'on_track'
    END,
    child.description,
    child.created_by_email,
    child.updated_by_email
FROM public.visibility_roadmap_items child
JOIN public.visibility_roadmap_items parent ON parent.id = child.parent_roadmap_id
ON CONFLICT (provider_roadmap_id, consumer_roadmap_id) DO NOTHING;

